// Pure screen-building functions for the Telegram bot. No network I/O, no
// mutable state — both live in server.js. Every export here is a plain
// data-in/data-out transform, unit-tested by tests/bot-ui-check.mjs.
//
// ctx = { contacts, from, isOwner }:
//  - contacts: the CONTACTS object server.js loads from assets/contacts.js
//    (may be null — every renderer here must still work).
//  - from: the Telegram `from` user object off the update (may be absent).
//  - isOwner: true when the chat is one of TG_LEAD_CHAT_IDS.
//
// Content (site-sourced facts) comes from bot-content.js (generated by
// gen-bot-content.mjs — regenerate it after any site text/price change).
// Bot-only microcopy (buttons, prompts, toasts) is typed out here, limited to
// the strings given in bot-ux SPEC.md sections 3-5 and FIXES.md section B —
// nothing improvised.
//
// Layout rules (FIXES.md section B): every content screen ends with a row that
// holds "← Меню"; two buttons share a row only when both labels are at most
// 17 characters (back-button pairs "← X" / "← Меню" are short by design);
// list lines start with "• "; prices never break inside "от 7 000 ₽".

const C = require('./bot-content.js');

// Lookups keyed by callback_data must only ever hit own keys: "constructor",
// "__proto__" or "toString" from a crafted button must not resolve to
// Object.prototype members.
function hasOwn(obj, key) { return Object.prototype.hasOwnProperty.call(obj, key); }

