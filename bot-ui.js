// "q12" / "l:o3": a position in a list, or -1 when out of range.
function indexIn(list, digits) {
  const n = Number(digits);
  return Number.isInteger(n) && n >= 0 && n < list.length ? n : -1;
}

function route(data) {
  const d = typeof data === 'string' ? data : '';
  const fixed = FIXED_ROUTES.get(d);
  if (fixed) return Object.assign({}, fixed);
  let m;
  if ((m = /^q(\d{1,3})$/.exec(d))) {
    const n = indexIn(C.faq, m[1]);
    return n < 0 ? null : { type: 'faqAnswer', n };
  }
  if ((m = /^s:([a-z]{1,20})(?::(w|f|q(\d{1,3})))?$/.exec(d))) {
    const id = m[1];
    // A service without a page has one screen: no steps, no FAQ.
    if (hasOwn(EXTRA_SERVICES, id)) return m[2] ? null : { type: 'extraService', id };
    if (!hasOwn(C.services, id)) return null;
    if (!m[2]) return { type: 'service', id };
    if (m[2] === 'w') return { type: 'serviceSteps', id };
    if (m[2] === 'f') return { type: 'serviceFaqList', id };
    const n = indexIn(C.services[id].faq, m[3]);
    return n < 0 ? null : { type: 'serviceFaqAnswer', id, n };
  }
  // Anything else under "l" is a request-form button that no longer exists
  // or never did (old "l:edit", an option out of range, an unknown service):
  // the flow answers it as stale and offers the menu.
  if (d === 'l' || d.indexOf('l:') === 0) {
    if ((m = /^l:o(\d{1,2})$/.exec(d))) {
      const n = indexIn(LEAD_SERVICES, m[1]);
      if (n >= 0) return { type: 'leadOption', n };
    }
    if ((m = /^l:([a-z]{1,20})$/.exec(d)) && hasOwn(SERVICE_ID_TO_LM_INDEX, m[1])) return { type: 'leadStartService', id: m[1] };
    return { type: 'leadUnknown' };
  }
  return null;
}

const FLOW_ROUTE_TYPES = new Set([
  'leadStart', 'leadStartService', 'leadOption', 'leadUseName', 'leadSkip', 'leadConfirm', 'leadCancel',
  'leadEditMenu', 'leadEditField', 'leadBack', 'leadUnknown',
]);
function isFlowRoute(r) { return !!r && FLOW_ROUTE_TYPES.has(r.type); }

// Typed commands -> routes (section 3's command table).
function commandRoute(command) {
  const cmd = String(command || '').toLowerCase();
  if (cmd === 'start' || cmd === 'menu' || cmd === 'help') return { type: 'menu' };
  if (cmd === 'services') return { type: 'services' };
  if (cmd === 'prices') return { type: 'prices' };
  if (cmd === 'faq') return { type: 'faqList' };
  if (cmd === 'contacts') return { type: 'contacts' };
  if (cmd === 'about') return { type: 'about' };
  if (cmd === 'reviews') return { type: 'reviews' };
  if (cmd === 'request') return { type: 'leadStart' };
  if (cmd === 'cancel') return { type: 'menu' }; // caller cancels the active flow as a side effect first
  return { type: 'menu' }; // unknown commands -> menu
}

// /start <payload> deep link. The owner-code check happens in server.js
// before this is ever consulted.
function startPayloadRoute(payload) {
  const p = String(payload || '').toLowerCase();
  if (p === 'request') return { type: 'leadStart' };
  if (SERVICE_IDS.includes(p)) return { type: 'service', id: p };
  if (EXTRA_IDS.includes(p)) return { type: 'extraService', id: p };
  if (p === 'prices') return { type: 'prices' };
  if (p === 'faq') return { type: 'faqList' };
  if (p === 'contacts') return { type: 'contacts' };
  if (p === 'about') return { type: 'about' };
  if (p === 'reviews') return { type: 'reviews' };
  return { type: 'menu' };
}

