// Zero-width, soft-hyphen, bidi and other invisible format characters are cut,
// and so are the blank "letters" that pass a letter check yet show nothing
// (FIXES G5): the Hangul fillers U+115F, U+1160, U+3164, U+FFA0, the braille
// blank U+2800, the Khmer inherent vowels U+17B4/U+17B5 and the Mongolian vowel
// separator U+180E. Control characters (newline, tab, ...) become a space.
const NAME_INVISIBLE_RE = /[\u00AD\u115F\u1160\u17B4\u17B5\u180E\u200B-\u200F\u202A-\u202E\u2060\u2066-\u2069\u2800\u3164\uFEFF\uFFA0]/g;
const NAME_CONTROL_RE = /\p{Cc}/gu;
function cleanName(raw) {
  return String(raw == null ? '' : raw)
    .replace(NAME_INVISIBLE_RE, '')
    .replace(NAME_CONTROL_RE, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

// Typed name: 1-80 characters after cleaning, at least one letter.
function validateName(raw) {
  const v = cleanName(raw);
  if (v.length < 1 || v.length > 80 || !/\p{L}/u.test(v)) return { ok: false };
  return { ok: true, value: v };
}

// Whole code points, at most `max` UTF-16 units: a cut through a surrogate
// pair is invalid text that Telegram rejects with the whole message.
function cutUnits(s, max) {
  let out = '';
  for (const ch of String(s)) {
    if (out.length + ch.length > max) break;
    out += ch;
  }
  return out;
}

// The client's Telegram first name for the "Меня зовут …" shortcut, cleaned
// like a typed name (no letter rule: it is their own profile name). '' when
// nothing visible is left — then the shortcut is not offered.
function telegramName(from) {
  const f = from && typeof from === 'object' ? from : {};
  return typeof f.first_name === 'string' ? cutUnits(cleanName(f.first_name), 80) : '';
}

