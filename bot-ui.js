// A Telegram user id fit for a tg://user link (a positive integer, as
// Telegram sends it), or '' — then no link is built rather than a dead one.
function telegramUserId(f) {
  const id = f.id;
  if (typeof id === 'number' && Number.isSafeInteger(id) && id > 0) return String(id);
  if (typeof id === 'string' && /^[1-9][0-9]{0,15}$/.test(id)) return id;
  return '';
}

