// 10-11 digits starting 7/8/9 -> "+7 XXX XXX-XX-XX"; otherwise the user's
// trimmed input as-is. The result still has to pass server.js's phoneOk()
// — the same check /api/lead applies — before the bot takes it.
function normalizePhone(raw) {
  const v = String(raw == null ? '' : raw).trim();
  const digits = v.replace(/\D/g, '');
  let ten = null;
  if (digits.length === 10 && /^[79]/.test(digits)) ten = digits;
  else if (digits.length === 11 && /^[78]/.test(digits)) ten = digits.slice(1);
  if (!ten) return v;
  return '+7 ' + ten.slice(0, 3) + ' ' + ten.slice(3, 6) + '-' + ten.slice(6, 8) + '-' + ten.slice(8, 10);
}

// A shared contact's number. Telegram sends international numbers without
// "+": Russian ones are formatted like a typed number, any other one that
// starts with a digit gets its "+".
function contactPhone(raw) {
  const v = String(raw == null ? '' : raw).trim();
  const n = normalizePhone(v);
  if (n !== v) return n;
  return /^\d/.test(v) ? '+' + v : v;
}

