function screenService(id) {
  if (!hasOwn(C.services, id)) return null;
  const svc = C.services[id];
  // A page whose only price caption is "Стоимость" itself (razdel) shows just
  // the number under the heading, like the other pages show "caption — price".
  const prices = svc.prices.map((p) => (p.caption === PRICE_HEADING ? b(nbspPrice(p.price)) : priceLine(p.caption, p.price)));
  const text = [
    b(svc.title),
    i(svc.tagline),
    '',
    esc(svc.intro),
    '',
    b('Что входит в услугу'),
    bullets(svc.includes.map((c) => c.text)),
    '',
    b(PRICE_HEADING),
    prices.join('\n'),
  ].join('\n');
  const rows = [[btn(LBL_REQUEST, 'l:' + id)], [btn(LBL_HOW, 's:' + id + ':w')]];
  if (svc.faq.length) rows.push([btn(LBL_SERVICE_FAQ, 's:' + id + ':f')]);
  rows.push([urlBtn(LBL_SITE_PAGE, C.siteUrl + svc.slug)]);
  rows.push([btn(LBL_SERVICES_BACK, 's'), btn(LBL_MENU_BACK, 'm')]);
  return { text, keyboard: kb(rows), linkPreview: DISABLE_PREVIEW };
}

