function escapeHtml(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}
const esc = escapeHtml;
function b(s) { return '<b>' + esc(s) + '</b>'; }
function i(s) { return '<i>' + esc(s) + '</i>'; }
function bullets(items) { return items.map((t) => '• ' + esc(t)).join('\n'); }
function numberedList(items) { return items.map((t, n) => (n + 1) + '. ' + esc(t)).join('\n'); }
// "от 7 000 ₽" -> the same with U+00A0 inside: Telegram must not wrap a price
// across lines. Only the "от … ₽" part is glued ("/ точка" after it is not).
function nbspPrice(price) {
  return String(price).replace(/(?:от\s)?\d[\d\s]*₽/g, (m) => m.replace(/\s/g, '\u00A0'));
}
function priceLine(label, price) { return esc(label) + ' — ' + b(nbspPrice(price)); }
function numberedBlock(s) { return b(s.n + ' · ' + s.title) + '\n' + esc(s.desc); }
function titleDescBlock(item) { return b(item.title) + '\n' + esc(item.desc); }
function bulletTitleDescLine(item) { return '• ' + b(item.title) + ' — ' + esc(item.desc); }
function qaBlock(item) { return b(item.q) + '\n' + esc(item.a); }

function btn(text, data) { return { text, callback_data: data }; }
function urlBtn(text, url) { return { text, url }; }
function kb(rows) { return { inline_keyboard: rows }; }
// Buttons "1".."N", three to a row: the questions themselves are listed in
// the screen text, too long for button labels.
function numberRows(count, dataFor) {
  const rows = [];
  for (let n = 0; n < count; n++) {
    if (n % 3 === 0) rows.push([]);
    rows[rows.length - 1].push(btn(String(n + 1), dataFor(n)));
  }
  return rows;
}

